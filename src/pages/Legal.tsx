/** Stránky obchodních podmínek a ochrany soukromí. */
export function Legal({ kind }: { kind: keyof typeof CONTENT }) {
  const { title, body } = CONTENT[kind];

  const renderText = (text: string) => {
    const urlPattern = /(https?:\/\/[^\s]+)/g;

    return text.split(urlPattern).map((part, index) => {
      if (part.startsWith('https://') || part.startsWith('http://')) {
        const url = part.replace(/[.,;]$/, '');

        return (
          <a
            key={index}
            href={url}
            target="_blank"
            rel="noopener noreferrer"
          >
            {url}
          </a>
        );
      }

      return part;
    });
  };

  return (
    <article className="prose">
      <h1>{title}</h1>

      {body.map((paragraph, index) => {
        const isHeading = /^\d+\.\s+[A-ZÁČĎÉĚÍŇÓŘŠŤÚŮÝŽ]/.test(
          paragraph
        );

        if (isHeading) {
          return <h2 key={index}>{paragraph}</h2>;
        }

        return <p key={index}>{renderText(paragraph)}</p>;
      })}
    </article>
  );
}
